def c_string(text):
    return '"' + "".join("\\x%02X" % byte for byte in text.encode("utf-8")) + '"'


def main():
    if len(sys.argv) != 3:
        sys.exit("usage: make-emoji-shortcodes.py emoji.json GEMOJI_COMMIT")
    with open(sys.argv[1], encoding="utf-8") as source:
        entries = json.load(source)
    pairs = sorted((alias, entry["emoji"]) for entry in entries for alias in entry["aliases"])

    lines = [
        "// ObjcMarkdown: every GitHub emoji shortcode, for macOS (GNUstep uses",
        "// OMEmojiShortcodes.inc). Generated by tools/emoji/make-emoji-shortcodes.py",
        "// from github/gemoji %s db/emoji.json; don't edit by hand:" % sys.argv[2],
        "//",
        NOTICE.rstrip("\n"),
        "",
        "typedef struct {",
        "    const char *name;",
        "    const char *emoji;",
        "} OMEmojiShortcodeString;",
        "",
        "static const OMEmojiShortcodeString OMEmojiShortcodesAll[] = {",
    ]
    lines += ['    { "%s", %s },' % (alias, c_string(emoji)) for alias, emoji in pairs]
    lines += ["};", ""]

    root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    with open(os.path.join(root, "ObjcMarkdown", "OMEmojiShortcodesAll.inc"), "w", newline="\n") as out:
        out.write("\n".join(lines))
    print("%d shortcodes" % len(pairs))


if __name__ == "__main__":
    main()
